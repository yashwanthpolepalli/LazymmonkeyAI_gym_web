    def verify_webhook(self, payload_body: bytes, signature: str) -> bool:
        """Validates incoming Razorpay webhook signature."""
        if not self.webhook_secret or not signature:
            return False
        secret_bytes = self.webhook_secret.encode("utf-8")
        generated_signature = hmac.new(secret_bytes, payload_body, hashlib.sha256).hexdigest()
        return hmac.compare_digest(generated_signature, signature)

    async def create_refund(
        self,
        payment_id: str,
        amount: Optional[float] = None,
        notes: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Creates a full or partial refund for a captured Razorpay payment."""
        payload: Dict[str, Any] = {"notes": notes or {}}
        if amount is not None and amount > 0:
            payload["amount"] = int(round(amount * 100))

        async with httpx.AsyncClient(timeout=15.0) as client:
            res = await client.post(
                f"{RAZORPAY_API_BASE}/payments/{payment_id}/refund",
                json=payload,
                headers=self._get_auth_header(),
            )
            if res.status_code not in (200, 201):
                err_msg = res.json().get("error", {}).get("description", res.text)
                raise ValueError(f"Failed to process refund: {err_msg}")
            return res.json()
